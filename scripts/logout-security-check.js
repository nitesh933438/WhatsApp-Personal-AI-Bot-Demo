const fs = require('fs');
const assert = require('assert');
const server = fs.readFileSync('server.js', 'utf8');
const sw = fs.readFileSync('public/sw.js', 'utf8');
const app = fs.readFileSync('public/js/app.js', 'utf8');
const auth = fs.readFileSync('routes/auth.js', 'utf8');
assert(server.indexOf('app.get("/login.html"') < server.indexOf('app.use(express.static'), 'login no-store route must precede static middleware');
assert(server.includes('no-store, no-cache, must-revalidate, private'), 'login must be no-store');
assert(sw.includes('request.mode === "navigate"'), 'service worker must bypass navigation requests');
assert(!sw.includes('caches.match("/login.html")'), 'service worker must not use cached login fallback');
assert(app.includes("localStorage.removeItem('token')") && app.includes("location.replace('/login.html')"), 'logout must clear client token and return to login');
assert(auth.includes('router.post("/logout"'), 'logout endpoint must exist');
console.log('Logout/security regression checks PASS');
